    public static S100DatasetDiscoveryMetadata unmarshallS100DatasetDiscoveryMetadata(String metadataXml) throws JAXBException {
        return unmarshalCatalogueObject(metadataXml, S100DatasetDiscoveryMetadata.class);
    }

    /**
     * This helper function will read the provided certificate and will generate
     * a minified version of its PEM representation, i.e. the ASCII characters of
     * the Base64 encoded certificate DER content, without the PEM header and
     * footer lines. Turned into a string it is the exact inverse of
     * {@link #getCertFromPem(String)}.
     * <p/>
     * Note that this is the <b>textual</b> PEM representation. The certificate
     * and signature elements of the S-100 protection scheme are typed
     * xs:base64Binary, which JAXB Base64-encodes on its own, so those elements
     * must be handed the DER content of {@link #getDerFromCert(X509Certificate)}
     * instead - passing them the PEM text would encode the certificate twice.
     *
     * @param cert the X.509 certificate to be read
     * @return the minified PEM representation of the certificate
     * @throws CertificateEncodingException if the provided certificate is invalid
     */
    public static byte[] getPemFromCert(X509Certificate cert) throws CertificateEncodingException {
        return Base64.getEncoder().encode(cert.getEncoded());
    }

    /**
     * This helper function will read the provided certificate and will return
     * its DER content, for embedding into the xs:base64Binary-typed certificate
     * elements of the S-100 protection scheme.
     * <p/>
     * S-100 Part 15, clauses 15-8.6 and 15-8.11.1, require such an element to
     * carry the Base64 encoded X.509 certificate - "When embedding the digital
     * certificates in XML elements, the header and footer lines are omitted" -
     * so a single Base64 decode of the element content has to yield the
     * certificate itself. Since JAXB performs that Base64 encoding for the
     * xs:base64Binary value, the value it is given must be the raw DER content.
     *
     * @param cert the X.509 certificate to be read
     * @return the DER content of the certificate
     * @throws CertificateEncodingException if the provided certificate is invalid
     */
    public static byte[] getDerFromCert(X509Certificate cert) throws CertificateEncodingException {
        return cert.getEncoded();
    }

    /**
     * This helper function will read the provided PEM input and reconstruct the
     * valid X509 certificate.
     *
     * @param certificatePem the certificate PEM input, i.e. the Base64 encoded
     *                       certificate without the PEM header and footer lines
     * @return the valid X509 certificate
     * @throws CertificateException if the provided PEM file is invalid
     */
    public static X509Certificate getCertFromPem(String certificatePem) throws CertificateException {
        // First decode the Base64 encoded PEM format
        final byte[] decodedPem = Base64.getDecoder().decode(certificatePem);

        // Then reconstruct the X509Certificate object
        return (X509Certificate) CertificateFactory.getInstance("X.509")
                .generateCertificate(new ByteArrayInputStream(decodedPem));
    }

    /**
     * Populates and return an S-100 surface property based on the provided
     * surface geometry coordinates.
     *
     * @param coords    The coordinates of the element to be generated
     * @return The populated point property
     */
    protected static PolygonPatchType generateSurfacePropertyPatch(Double[] coords) {
        // Create an OpenGIS GML factory
        net.opengis.gml._3.ObjectFactory opengisGMLFactory = new net.opengis.gml._3.ObjectFactory();

        // Generate the elements
        PolygonPatchType polygonPatchType = new PolygonPatchType();
        AbstractRingPropertyType abstractRingPropertyType = new AbstractRingPropertyType();
        LinearRingType linearRingType = new LinearRingType();
        PosList posList = new PosList();

        // Populate with the geometry data
        posList.setValue(coords);

        // Populate the elements
        linearRingType.setPosList(posList);
        abstractRingPropertyType.setAbstractRing(opengisGMLFactory.createLinearRing(linearRingType));
        polygonPatchType.setExterior(abstractRingPropertyType);

        // And return the output
        return polygonPatchType;
    }

    /**
     * Populates and returns the GML polygon used as the bounding polygon of a
     * single S-100 data coverage entry.
     * <p/>
     * S-100 Part 17, S100_DataCoverage NOTE 1 restricts the bounding polygon to
     * "a single GML Polygon with one exterior and 0 or more interiors expressed
     * as Linear Rings using SRS EPSG:4326", so the shell and the holes of a
     * polygon are encoded as separate linear rings and never merged. Any other
     * (non-polygonal) geometry is described by its envelope, which is the
     * smallest rectangle satisfying the closed, at least 4 positions rule.
     *
     * @param geometry the Java geometry object, not a geometry collection
     * @return The populated bounding polygon
     */
    protected static PolygonType generateBoundingPolygon(Geometry geometry) {
        // Generate the elements
        final PolygonType polygonType = new PolygonType();

        // NOTE 1 also requires a valid GML identifier for the polygon
        polygonType.setId(BOUNDING_POLYGON_ID_PREFIX + BOUNDING_POLYGON_ID_COUNTER.getAndIncrement());
        // NOTE 1 fixes the SRS of the bounding polygon to EPSG:4326, whose axis order is
        // the latitude/longitude order the ring coordinates are written in below
        polygonType.setSrsName(BOUNDING_POLYGON_SRS_NAME);
        // srsDimension is the coordinate dimension (lat/lon), not the SRID
        polygonType.setSrsDimension(BigInteger.TWO);

        // Populate the exterior and the optional interiors
        if(geometry instanceof Polygon polygon) {
            polygonType.setExterior(generateLinearRingProperty(polygon.getExteriorRing().getCoordinates()));
            final List<AbstractRingPropertyType> interiors = new ArrayList<>();
            for(int i=0; i<polygon.getNumInteriorRing(); i++) {
                interiors.add(generateLinearRingProperty(polygon.getInteriorRingN(i).getCoordinates()));
            }
            if(!interiors.isEmpty()) {
                polygonType.setInteriors(interiors);
            }
        } else {
            polygonType.setExterior(generateLinearRingProperty(envelopeToRingCoordinates(geometry)));
        }

        // And return the output
        return polygonType;
    }

    /**
     * Populates and returns an S-100 linear ring property based on the provided
     * ring geometry coordinates.
     * <p/>
     * Per S-100 Part 17, S100_DataCoverage NOTE 1 the exterior and the optional
     * interiors "shall be composed of a closed sequence of >=4 coordinate
     * positions", which is validated here so that non-conformant rings are
     * rejected instead of being marshalled.
     *
     * @param coordinates The ring coordinates of the element to be generated
     * @return The populated ring property
     */
    protected static AbstractRingPropertyType generateLinearRingProperty(Coordinate[] coordinates) {
        // Sanity check
        if(coordinates.length < 4 || !coordinates[0].equals2D(coordinates[coordinates.length-1])) {
            throw new IllegalArgumentException("The S-100 data coverage bounding polygon rings must be closed "
                    + "sequences of at least 4 coordinate positions (S-100 Part 17, S100_DataCoverage NOTE 1)");
        }

        // Create an OpenGIS GML factory
        net.opengis.gml._3.ObjectFactory opengisGMLFactory = new net.opengis.gml._3.ObjectFactory();

        // Generate the elements
        AbstractRingPropertyType abstractRingPropertyType = new AbstractRingPropertyType();
        LinearRingType linearRingType = new LinearRingType();
        PosList posList = new PosList();

        // Populate with the geometry data
        posList.setValue(coordinatesToArray(coordinates)
                .stream()
                .flatMap(Stream::of)
                .toArray(Double[]::new));

        // Populate the elements
        linearRingType.setPosList(posList);
        abstractRingPropertyType.setAbstractRing(opengisGMLFactory.createLinearRing(linearRingType));

        // And return the output
        return abstractRingPropertyType;
    }

    /**
     * A simple utility function that returns the closed ring of coordinates
     * describing the envelope of the provided geometry.
     *
     * @param geometry the provided geometry
     * @return the closed ring of coordinates of the geometry envelope
     */
    protected static Coordinate[] envelopeToRingCoordinates(Geometry geometry) {
        final Envelope envelope = geometry.getEnvelopeInternal();

        // Sanity check
        if(envelope.isNull()) {
            throw new IllegalArgumentException("The S-100 data coverage bounding polygon cannot be generated for "
                    + "an empty geometry (S-100 Part 17, S100_DataCoverage NOTE 1)");
        }

        // And return the envelope rectangle, closed as required
        return new Coordinate[] {
                new Coordinate(envelope.getMinX(), envelope.getMinY()),
                new Coordinate(envelope.getMaxX(), envelope.getMinY()),
                new Coordinate(envelope.getMaxX(), envelope.getMaxY()),
                new Coordinate(envelope.getMinX(), envelope.getMaxY()),
                new Coordinate(envelope.getMinX(), envelope.getMinY())
        };
    }

    /**
     * A simple utility function that receives JTS geometry coordinates and
     * constructs a list of the coordinate values arrays.
     *
     * @param coordinates the provided coordinates
     * @return the respective list of coordinate values arrays
     */
    protected static List<Double[]> coordinatesToArray(Coordinate[] coordinates) {
        // Translate the coordinates to a simple list of doubles (Y, X), i.e.
        // latitude followed by longitude, which is the EPSG:4326 axis order
        // mandated for the bounding polygons by S-100 Part 17
        return Optional.ofNullable(coordinates)
                .map(Arrays::asList)
                .orElse(Collections.emptyList())
                .stream()
                .map(c -> new Double[]{c.getY(), c.getX()})
                .toList();
    }

